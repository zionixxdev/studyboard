#!/usr/bin/env node
// Reads .env and writes js/config.js. Keeps the frontend buildless while still
// letting you keep real values out of git (js/config.js is git-ignored).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");

if (!existsSync(envPath)) {
  console.error("No .env found. Copy .env.example to .env first.");
  process.exit(1);
}

const env = {};
for (const line of readFileSync(envPath, "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}

if (!env.SUPABASE_URL || !env.SUPABASE_ANON_KEY) {
  console.error(".env must define SUPABASE_URL and SUPABASE_ANON_KEY.");
  process.exit(1);
}

const turn = env.TURN_URL
  ? `  { urls: ${JSON.stringify(env.TURN_URL)}, username: ${JSON.stringify(env.TURN_USERNAME || "")}, credential: ${JSON.stringify(env.TURN_CREDENTIAL || "")} },\n`
  : "";

const out = `// GENERATED by scripts/gen-config.mjs — do not edit by hand.
export const SUPABASE_URL = ${JSON.stringify(env.SUPABASE_URL)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(env.SUPABASE_ANON_KEY)};

export const ICE_SERVERS = [
  { urls: "stun:stun.l.google.com:19302" },
  { urls: "stun:stun1.l.google.com:19302" },
${turn}];

export const MAX_FILE_BYTES = 25 * 1024 * 1024;
export const ALLOWED_MIME = [
  "application/pdf", "image/png", "image/jpeg", "image/webp", "image/gif",
];
export const MAX_CHAT_LEN = 2000;
export const MAX_NICK_LEN = 32;
export const MAX_ROOM_NAME_LEN = 80;

export const APP_NAME = "StudyBoard";
export const REPO_URL = "https://github.com/your-username/studyboard";
`;

writeFileSync(join(root, "js", "config.js"), out);
console.log("Wrote js/config.js");
